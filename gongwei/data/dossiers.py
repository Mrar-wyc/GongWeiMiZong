# --------------------------------------------------------------------------
# 便捷构造
# --------------------------------------------------------------------------


def D(did: str, title: str, body: str, act: int = 1, time_code: str = "",
      place_code: str = "", people=(), clues=(), items=(), flags=(), trust=(),
      score: int = 0, links=(), requires=None,
      found_msg: str = "//得到新档案——收录至档目//") -> Dossier:
    """一条档案。

    ``time_code``/``place_code``/``people`` 不写就按档号推：档号本身就是
    「时-地-人」的索引，写两遍容易写岔。
    """
    parts = did.split("-")
    tc = time_code or parts[0]
    pc = place_code or (parts[1] if len(parts) > 1 else "")
    ppl = tuple(people) if people else tuple(parts[2:])
    return Dossier(
        id=did,
        title=title,
        act=act,
        time_code=tc,
        place_code=pc,
        people=ppl,
        body=body.strip(),
        links=tuple(links),
        requires=requires,
        effect=Effect(add_clues=tuple(clues), add_items=tuple(items),
                      flags=tuple(flags), trust=tuple(trust), score=score),
        found_msg=found_msg,
    )


