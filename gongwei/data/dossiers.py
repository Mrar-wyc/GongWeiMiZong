#: 第一幕的幕末总录。第一幕那道门槛就挂在它身上（见 ``story.CRIME_SCENE``）。
#: 它自己又有 ``requires``：上面那些格目没读全，敲这个号子也打不开。
FIRST_ACT_SUMMARY: str = "01-FY-END"


def read_act1(engine) -> List[str]:  # noqa: ANN001 - 避免为了一个类型注解引入循环导入
    """像玩家那样把第一幕的档案读一遍，返回实际读到的档号。

    引擎不在这里做任何检查——``read_dossier`` 自己会在 ``can_read_dossier``
    不通过时抛错，那正是我们要暴露的问题。
    """
    read: List[str] = []
    for did in ACT1_READING_ORDER:
        if engine.state.dossier_read(did):
            continue
        engine.read_dossier(did)
        read.append(did)
    # 幕末总录：它要等前面几份读完才打得开，所以放在最后。
    if not engine.state.dossier_read(FIRST_ACT_SUMMARY):
        engine.read_dossier(FIRST_ACT_SUMMARY)
        read.append(FIRST_ACT_SUMMARY)
    return read


def build_dossiers() -> Dict[str, Dossier]:
    out: Dict[str, Dossier] = {}
    for d in DOSSIERS:
        if d.id in out:
            raise ValueError(f"重复的档号：{d.id}")
        out[d.id] = d
    return out
